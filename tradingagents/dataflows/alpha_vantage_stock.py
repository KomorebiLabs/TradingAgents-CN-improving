"""
【为什么要用调整后的数据 (Adjusted Close)】

股票价格会因为以下原因「调整」：

1. 股息发放 (Dividends)
   - 公司发放股息时，股价会下跌
   - 但这只是资金转移，不影响股东总回报
   - 调整后价格会扣除股息再投资的影响

2. 拆股 (Stock Splits)
   - 例如 1 股拆成 2 股，股价变为原来的一半
   - 但股东持有的总价值不变
   - 调整后价格会考虑拆股比例

示例：
  假设某股票：
    - 2020-01-01: 收盘价 $100
    - 2020-06-01: 每股分红 $5
    - 2020-06-02: 股价变为 $95（市场自动调整）

  未调整的收盘价：$95
  调整后收盘价：$100（考虑股息再投资）

对于长期分析和回测，调整后价格更准确。

================================================================================
【outputsize 选择的考虑】

compact vs full 的权衡：

┌─────────────────────────────────────────────────────────────────────────────┐
│                          compact 模式                                       │
├─────────────────────────────────────────────────────────────────────────────┤
│  优点：                                                                    │
│    ✓ API 调用轻量                                                          │
│    ✓ 返回数据量小                                                          │
│    ✓ 适合短期分析                                                          │
│                                                                             │
│  缺点：                                                                    │
│    ✗ 最多 100 个交易日（约 5 个月）                                        │
│    ✗ 无法获取长期历史数据                                                  │
│    ✗ 如果 start_date 太早，会获取不到数据                                   │
└─────────────────────────────────────────────────────────────────────────────┘

┌─────────────────────────────────────────────────────────────────────────────┐
│                          full 模式                                          │
├─────────────────────────────────────────────────────────────────────────────┤
│  优点：                                                                    │
│    ✓ 可获取 20 年历史数据                                                  │
│    ✓ 适合长期分析                                                          │
│    ✓ 总是能获取完整的历史                                                  │
│                                                                             │
│  缺点：                                                                    │
│    ✗ API 配额消耗更多                                                      │
│    ✗ 返回数据量大                                                          │
│    ✗ 处理时间更长                                                          │
└─────────────────────────────────────────────────────────────────────────────┘

本模块的策略：
  - 动态选择：如果 start_date 距离今天 < 100 天，用 compact
  - 否则用 full
  - 这样可以节省 API 配额，同时保证数据完整性

================================================================================
【与 Yahoo Finance 的对比】

Yahoo Finance (yfinance) 的优势：
  - 免费
  - 返回数据完整
  - 支持批量下载

Alpha Vantage 的优势：
  - 数据质量高
  - API 稳定
  - 支持更多技术指标

TradingAgents 使用 interface.py 中的路由机制：
  - 优先使用 Alpha Vantage
  - 如果触发频率限制，自动切换到 Yahoo Finance
"""
