from datetime import datetime
# 从 alpha_vantage_common 导入底层工具函数
from .alpha_vantage_common import _make_api_request, _filter_csv_by_date_range


# ==============================================================================
# 核心函数
# ==============================================================================

def get_stock(
    symbol: str,
    start_date: str,
    end_date: str
) -> str:
    """
    获取指定股票的历史 OHLCV 行情数据。

    这个函数是 Alpha Vantage 股票数据的统一入口：

        ┌─────────────────────────────────────────────────────────────────┐
        │                     get_stock() 函数流程                          │
        │                                                                  │
        │    输入：symbol="NVDA", start_date="2024-01-01", end_date="..."   │
        │                                                                  │
        │         │                                                        │
        │         ▼                                                        │
        │    ┌─────────────────────┐                                       │
        │    │ 解析日期            │                                       │
        │    │ start_dt = datetime │                                       │
        │    └─────────────────────┘                                       │
        │         │                                                        │
        │         ▼                                                        │
        │    ┌─────────────────────┐                                       │
        │    │ 计算距今天数        │                                       │
        │    │ days = (today-start)│                                       │
        │    └─────────────────────┘                                       │
        │         │                                                        │
        │         ▼                                                        │
        │    ┌─────────────────────────────────────────┐                   │
        │    │ 决定 outputsize                          │                   │
        │    │ if days < 100: outputsize = "compact"   │                   │
        │    │ else: outputsize = "full"               │                   │
        │    └─────────────────────────────────────────┘                   │
        │         │                                                        │
        │         ▼                                                        │
        │    ┌─────────────────────────────────────────┐                   │
        │    │ 调用 Alpha Vantage API                  │                   │
        │    │ _make_api_request("TIME_SERIES_DAILY_   │                   │
        │    │   ADJUSTED", params)                    │                   │
        │    └─────────────────────────────────────────┘                   │
        │         │                                                        │
        │         ▼                                                        │
        │    ┌─────────────────────────────────────────┐                   │
        │    │ 按日期范围过滤                          │                   │
        │    │ _filter_csv_by_date_range(response,    │                   │
        │    │   start_date, end_date)                 │                   │
        │    └─────────────────────────────────────────┘                   │
        │         │                                                        │
        │         ▼                                                        │
        │    输出：CSV 格式的行情数据                                        │
        │                                                                  │
        └─────────────────────────────────────────────────────────────────┘

    Args:
        symbol: 股票代码
                例如：IBM, AAPL, NVDA, TSLA
                注意：Alpha Vantage 通常要求大写

        start_date: 开始日期
                    格式：YYYY-MM-DD
                    例如：2024-01-01

        end_date: 结束日期
                  格式：YYYY-MM-DD
                  例如：2024-12-31

    Returns:
        CSV 格式的行情数据字符串

        格式：
            timestamp,open,high,low,close,adjusted_close,volume,dividend_amount,split_coefficient
            2024-01-02,183.89,185.30,183.25,184.25,184.25,43862100,0.00,1.0

    Raises:
        不直接抛出异常，错误会在底层 _make_api_request() 中处理

    示例：
        >>> data = get_stock("IBM", "2024-01-01", "2024-01-31")
        >>> print(data[:200])
        timestamp,open,high,low,close,adjusted_close,volume,dividend_amount,split_coefficient
        2024-01-02,183.89,185.30,183.25,184.25,184.25,43862100,0.00,1.0
    """
    # -------------------------------------------------------------------------
    # Step 1: 解析日期并计算时间范围
    # -------------------------------------------------------------------------
    # 将字符串日期转换为 datetime 对象
    start_dt = datetime.strptime(start_date, "%Y-%m-%d")
    today = datetime.now()

    # -------------------------------------------------------------------------
    # Step 2: 选择 outputsize
    # -------------------------------------------------------------------------
    #
    # Alpha Vantage 的 outputsize 参数决定返回多少数据：
    #
    #   compact 模式：
    #     - 返回最近 100 个交易日
    #     - API 调用不消耗太多配额
    #     - 适合短期分析
    #
    #   full 模式：
    #     - 返回完整历史数据（最多 20 年）
    #     - 消耗更多配额
    #     - 适合长期分析或训练数据
    #
    # 决策逻辑：
    #   - 如果请求的开始日期距离今天小于 100 天 → 用 compact
    #   - 否则 → 用 full（需要更早的历史数据）
    #
    # 示意图：
    #
    #   今天 ──────┬──────────────────────────────────► 时间
    #              │
    #              │◄───── 100 天 ─────►│
    #              │                    │
    #              │ start_date 在这    │ start_date 在这
    #              │ 用 compact         │ 用 full
    #              │                    │
    #
    days_from_today_to_start = (today - start_dt).days
    outputsize = "compact" if days_from_today_to_start < 100 else "full"

    # -------------------------------------------------------------------------
    # Step 3: 构建 API 参数
    # -------------------------------------------------------------------------
    params = {
        "symbol": symbol,           # 股票代码
        "outputsize": outputsize,  # 数据量选项
        "datatype": "csv",         # 返回 CSV 格式（比 JSON 更紧凑）
    }

    # -------------------------------------------------------------------------
    # Step 4: 调用 API
    # -------------------------------------------------------------------------
    # _make_api_request() 会：
    #   1. 添加 function="TIME_SERIES_DAILY_ADJUSTED"
    #   2. 添加 apikey
    #   3. 发送 HTTP GET 请求
    #   4. 检查频率限制错误
    #   5. 返回原始响应
    response = _make_api_request("TIME_SERIES_DAILY_ADJUSTED", params)

    # -------------------------------------------------------------------------
    # Step 5: 按日期范围过滤
    # -------------------------------------------------------------------------
    #
    # 为什么需要过滤？
    # ----------------
    # Alpha Vantage API 不支持指定日期范围获取数据：
    #   - compact 模式：返回最近 100 个交易日
    #   - full 模式：返回所有历史数据（可能 20 年）
    #
    # 但我们需要的是 start_date 到 end_date 之间的数据
    #
    # 解决方案：
    #   1. 获取完整响应
    #   2. 在本地按日期过滤
    #
    # 数据流：
    #
    #   API 返回（compact，假设请求一年前）：     本地过滤后：
    #   ┌──────────────────────────────┐         ┌──────────────────────────────┐
    #   │ 2024-01-01,183.89,...      │         │ 2024-01-01,183.89,...      │
    #   │ 2024-01-02,184.25,...      │         │ 2024-01-02,184.25,...      │
    #   │ ...                        │ 过滤 ──► │ ...                        │
    #   │ 2024-06-15,185.50,...      │         │ 2024-06-15,185.50,...      │
    #   │ 2024-06-16,...             │         └──────────────────────────────┘
    #   └──────────────────────────────┘         (只保留请求范围内数据)
    #
    return _filter_csv_by_date_range(response, start_date, end_date)


