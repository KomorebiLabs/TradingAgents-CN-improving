"""
模块文档: modes.py - 权限模式枚举定义

================================================================================
特殊Python语法说明:
1. from enum import Enum:
   Python内置的枚举类型模块，用于定义一组命名的常量值。
   枚举类的成员是单例，每个成员都有name和value两个属性。

2. class PermissionMode(str, Enum):
   - str: 让枚举成员表现得像字符串，可以直接比较和序列化
   - Enum: 提供枚举的基本功能
   这种写法让枚举值既是Enum成员又是str子类的实例。

3. 大写常量命名:
   枚举成员的名称使用全大写（如DEFAULT, PLAN），
   这是Python的约定，表示这些是常量。
================================================================================

功能说明:
    定义了OpenHarness支持的权限模式枚举。
    权限模式控制AI在执行敏感操作时是否需要用户确认。
"""

from __future__ import annotations

from enum import Enum


class PermissionMode(str, Enum):
    """
    =============================================================================
    类文档: PermissionMode - 权限模式枚举

    为什么需要这个类:
        AI代理可以执行各种工具（文件操作、bash命令等），
        其中一些是敏感操作（如删除文件、执行系统命令）。
        权限模式让用户控制是否需要手动确认这些操作。

    枚举成员说明:
        DEFAULT: 默认模式
            - 读取操作（只读工具）自动允许
            - 写入操作（修改文件、创建文件等）需要用户确认
        
        PLAN: 计划模式
            - AI只能分析、搜索、读取
            - 所有修改操作都被阻止
            - 适合让AI研究问题而不执行任何变更
        
        FULL_AUTO: 全自动模式
            - 所有操作都自动允许，不需要确认
            - 适合信任AI的自动化场景
            - ⚠️ 谨慎使用，存在安全风险

    使用场景示例:
        # 切换到计划模式（只读）
        /permissions plan
        
        # 切换到全自动模式
        /permissions full_auto
        
        # 恢复默认模式（需要确认）
        /permissions default
    =============================================================================
    """

    DEFAULT = "default"
    PLAN = "plan"
    FULL_AUTO = "full_auto"
